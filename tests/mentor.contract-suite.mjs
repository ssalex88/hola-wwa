import test from 'node:test'
import assert from 'node:assert/strict'

export const referenceAt = '2026-10-01T15:00:00.000Z'
export const configuration = { zone: 'Lima Centro', hours: 2, moment: 'Tarde', vehicle: 'Bicicleta', scheduleMode: 'now', scheduledDate: null, expenseFuel: 0, expenseMaintenance: 2, expenseOther: 0 }
export const unwrap = result => { assert.equal(result.ok, true, JSON.stringify(result)); assert.ok(Number.isInteger(result.revision)); return result.data }
export const expectError = (result, code) => { assert.equal(result.ok, false, JSON.stringify(result)); assert.equal(result.error.code, code); assert.ok(result.error.message); assert.equal('data' in result, false) }

/** A can run exactly these tests against a mock factory; no local internals used. */
export function mentorContractSuite(name, create) {
  test(`${name}: profiles, catalog, routes and snapshot reads are side-effect free`, async () => {
    const { service } = create()
    const profiles = unwrap(await service.listProfiles())
    assert.equal(profiles.length, 8)
    const catalog = unwrap(await service.getCatalog())
    assert.equal(catalog.zones.length, 5)
    assert.deepEqual(catalog.vehicles, ['Bicicleta', 'Moto', 'Auto'])
    const route = unwrap(await service.exploreRoute({ originZoneId: 'lima-centro', destinationZoneId: 'surco' }))
    assert.equal(route.affectsOrderAssignment, false)
    assert.equal(route.simulated, true)
    assert.equal(new Set(route.zones.map(z => z.id)).size, route.zones.length)
    assert.ok(route.zones.every(zone => catalog.zones.some(item => item.id === zone.id && item.label === zone.label)))
    const camila = unwrap(await service.getProfile('inactive-recent'))
    assert.equal(camila.contractVersion, '1.0')
    assert.equal(camila.clock.timeZone, 'America/Lima')
    assert.equal(camila.eligibility.eligible, true)
    assert.equal(camila.eligibility.daysInactive, 20)
    assert.equal(camila.eligibility.priority, 1)
    assert.equal(camila.progress.interventionStartedAt, null)
    assert.deepEqual(unwrap(await service.getProfile('inactive-recent')), camila)
    expectError(await service.getProfile('missing'), 'NOT_FOUND')
    expectError(await service.exploreRoute({ originZoneId: 'missing', destinationZoneId: 'surco' }), 'VALIDATION')
  })
  test(`${name}: goals and manual contributions are isolated, editable and never automatic`, async () => {
    const { service } = create(); let n = 0
    const ctx = () => ({ profileId: 'inactive-recent', requestId: `goal-${++n}` })
    let snapshot = unwrap(await service.saveGoal(ctx(), { name: 'Reparar mi bicicleta', targetAmount: 150, targetDate: null }))
    const goalId = snapshot.goals[0].id
    assert.equal(snapshot.goalProgress[0].contributedAmount, 0)
    snapshot = unwrap(await service.saveContribution(ctx(), { goalId, amount: 20, contributedOn: '2026-10-01' }))
    const contributionId = snapshot.contributions[0].id
    assert.deepEqual(snapshot.goalProgress[0], { goalId, contributedAmount: 20, remainingAmount: 130, progressPercent: 13.33, targetReached: false })
    assert.deepEqual(unwrap(await service.getProfile('inactive-31-60')).goals, [])
    expectError(await service.saveGoal(ctx(), { name: 'Otra meta', targetAmount: 50, targetDate: null }), 'CONFLICT')
    expectError(await service.saveContribution({ profileId: 'inactive-31-60', requestId: 'foreign' }, { goalId, amount: 5, contributedOn: '2026-10-01' }), 'NOT_FOUND')
    expectError(await service.saveContribution(ctx(), { goalId, amount: -1, contributedOn: '2026-10-01' }), 'VALIDATION')
    expectError(await service.saveContribution(ctx(), { goalId, amount: 1, contributedOn: '2026-10-02' }), 'VALIDATION')
    snapshot = unwrap(await service.saveContribution(ctx(), { goalId, contributionId, amount: 175.126, contributedOn: '2026-09-30' }))
    assert.equal(snapshot.goalProgress[0].contributedAmount, 175.13)
    assert.equal(snapshot.goalProgress[0].remainingAmount, 0)
    assert.equal(snapshot.goalProgress[0].targetReached, true)
    snapshot = unwrap(await service.deleteContribution(ctx(), { contributionId }))
    assert.equal(snapshot.goalProgress[0].contributedAmount, 0)
    snapshot = unwrap(await service.changeGoalStatus(ctx(), { goalId, status: 'archived' }))
    assert.equal(snapshot.goals[0].status, 'archived')
    snapshot = unwrap(await service.saveGoal(ctx(), { name: 'Nueva', targetAmount: 40, targetDate: '2026-10-02' }))
    expectError(await service.changeGoalStatus(ctx(), { goalId, status: 'active' }), 'CONFLICT')
    unwrap(await service.calculateProjection(ctx(), configuration))
    assert.deepEqual(unwrap(await service.getProfile('inactive-recent')).contributions, [])
  })
  test(`${name}: requestId replay, conflict and optimistic revision are stable`, async () => {
    const { service } = create()
    const ctx = { profileId: 'inactive-recent', requestId: 'one', expectedRevision: 0 }
    const input = { name: 'Meta', targetAmount: 100, targetDate: null }
    const first = await service.saveGoal(ctx, input)
    unwrap(first)
    assert.deepEqual(await service.saveGoal(ctx, { targetDate: null, targetAmount: 100, name: 'Meta' }), first)
    expectError(await service.saveGoal(ctx, { ...input, targetAmount: 101 }), 'CONFLICT')
    expectError(await service.activatePause(ctx, { endsAt: null, reason: null }), 'CONFLICT')
    expectError(await service.activatePause({ ...ctx, requestId: 'stale' }, { endsAt: null, reason: null }), 'CONFLICT')
    assert.equal(unwrap(await service.getProfile('inactive-recent')).revision, first.revision)
    unwrap(await service.saveGoal({ profileId: 'inactive-31-60', requestId: 'one', expectedRevision: 0 }, input))
  })
  test(`${name}: projections, independent comparison, unavailable and option lifecycle`, async () => {
    const { service } = create(); let n = 0
    const ctx = () => ({ profileId: 'inactive-recent', requestId: `projection-${++n}` })
    const projection = unwrap(await service.calculateProjection(ctx(), configuration))
    assert.equal(projection.status, 'available')
    assert.equal(projection.currency, 'PEN')
    assert.deepEqual([projection.result.grossMin, projection.result.grossMax, projection.result.afterExpensesMin, projection.result.afterExpensesMax], [24, 40, 22, 38])
    assert.ok(projection.incentives.every(i => i.guaranteed === false))
    const compared = unwrap(await service.compareProjections(ctx(), { first: configuration, second: { ...configuration, hours: 1, expenseMaintenance: 5 } }))
    assert.equal(compared.first.result.expenses, 2)
    assert.equal(compared.second.result.expenses, 5)
    assert.equal('winner' in compared, false)
    assert.equal(unwrap(await service.calculateProjection(ctx(), { ...configuration, vehicle: 'Auto' })).status, 'unavailable')
    expectError(await service.calculateProjection(ctx(), { ...configuration, hours: 0 }), 'VALIDATION')
    expectError(await service.calculateProjection(ctx(), { ...configuration, scheduleMode: 'other' }), 'VALIDATION')
    let snapshot = unwrap(await service.saveOption(ctx(), { projectionId: projection.id }))
    const optionId = snapshot.savedOptions[0].id
    assert.equal(snapshot.savedOptions[0].isReservation, false)
    assert.equal(snapshot.savedOptions[0].reminderId, null)
    const reviewed = unwrap(await service.reviewOption(ctx(), { optionId }))
    assert.equal(reviewed.projection.status, 'available')
    assert.notEqual(reviewed.projection.id, projection.id)
    assert.equal(reviewed.option.projectionId, reviewed.projection.id)
    snapshot = unwrap(await service.saveOption(ctx(), { projectionId: compared.second.id, optionId }))
    assert.equal(snapshot.savedOptions.length, 1)
    assert.equal(snapshot.savedOptions[0].configuration.hours, 1)
    expectError(await service.saveOption({ profileId: 'inactive-31-60', requestId: 'foreign-projection' }, { projectionId: projection.id }), 'NOT_FOUND')
    snapshot = unwrap(await service.deleteOption(ctx(), { optionId }))
    assert.deepEqual(snapshot.savedOptions, [])
  })
  test(`${name}: pause blocks contacts, cancels reminders and preserves prior preferences`, async () => {
    const { service, admin } = create(); let n = 0
    const ctx = () => ({ profileId: 'inactive-recent', requestId: `pause-${++n}` })
    const prefs = { allowProgramInvitations: true, channels: { app: true, external: true }, remindersAllowed: true, consentRecordedAt: referenceAt }
    unwrap(await service.updatePreferences(ctx(), prefs))
    const projection = unwrap(await service.calculateProjection(ctx(), configuration))
    let snapshot = unwrap(await service.saveOption(ctx(), { projectionId: projection.id }))
    const savedOptionId = snapshot.savedOptions[0].id
    snapshot = unwrap(await service.scheduleReminder(ctx(), { savedOptionId, scheduledAt: '2026-10-02T13:30:00.000Z', explicitConsent: true }))
    const reminderId = snapshot.reminders[0].id
    snapshot = unwrap(await service.activatePause(ctx(), { endsAt: '2026-10-03T15:00:00.000Z', reason: null }))
    assert.deepEqual(snapshot.preferences, prefs)
    assert.equal(snapshot.contactPermission.reason, 'paused')
    assert.equal(snapshot.reminders[0].status, 'cancelled')
    expectError(await service.scheduleReminder(ctx(), { savedOptionId, scheduledAt: '2026-10-02T15:00:00.000Z', explicitConsent: true }), 'CONTACT_BLOCKED')
    expectError(await service.presentInvitation(ctx(), { campaignId: 'pilot', origin: 'external', mode: 'simulated-contact' }), 'CONTACT_BLOCKED')
    const pauseId = snapshot.pause.id
    snapshot = unwrap(await service.updatePause(ctx(), { pauseId, endsAt: null, reason: 'Descanso' }))
    assert.equal(snapshot.pause.endsAt, null)
    unwrap(await service.endPause(ctx(), { pauseId }))
    snapshot = unwrap(await service.getProfile('inactive-recent'))
    assert.equal(snapshot.reminders[0].status, 'cancelled')
    assert.deepEqual(snapshot.preferences, prefs)
    unwrap(await admin.advanceClock({ observedAt: '2026-10-02T13:30:00.000Z' }))
    snapshot = unwrap(await admin.executeReminder(ctx(), { reminderId }))
    assert.equal(snapshot.reminders[0].executedAt, null)
    assert.equal(snapshot.reminders[0].status, 'cancelled')
  })
  test(`${name}: invitation preview, later, rejection, one contact and voluntary start`, async () => {
    const { service } = create(); let n = 0
    const ctx = () => ({ profileId: 'inactive-recent', requestId: `invite-${++n}` })
    let snapshot = unwrap(await service.presentInvitation(ctx(), { campaignId: 'pilot', origin: 'external', mode: 'demo-preview' }))
    const preview = snapshot.invitations[0]
    assert.equal(preview.presentedAt, null)
    assert.equal(snapshot.contactPermission.reason, 'allowed')
    expectError(await service.respondInvitation(ctx(), { invitationId: preview.id, response: 'decline', requestedFollowupAt: null }), 'CONFLICT')
    snapshot = unwrap(await service.presentInvitation(ctx(), { campaignId: 'pilot', origin: 'external', mode: 'simulated-contact' }))
    const contact = snapshot.invitations.find(i => i.mode === 'simulated-contact')
    const repeated = unwrap(await service.presentInvitation(ctx(), { campaignId: 'pilot', origin: 'external', mode: 'simulated-contact' }))
    assert.equal(repeated.invitations.length, 2)
    expectError(await service.presentInvitation(ctx(), { campaignId: 'pilot', origin: 'app', mode: 'simulated-contact' }), 'CONTACT_BLOCKED')
    snapshot = unwrap(await service.respondInvitation(ctx(), { invitationId: contact.id, response: 'later', requestedFollowupAt: null }))
    assert.equal(snapshot.invitations[1].requestedFollowupAt, null)
    const other = unwrap(await service.presentInvitation({ profileId: 'inactive-31-60', requestId: 'decline' }, { campaignId: 'pilot', origin: 'external', mode: 'simulated-contact' }))
    const declined = unwrap(await service.respondInvitation({ profileId: 'inactive-31-60', requestId: 'decline-response' }, { invitationId: other.invitations[0].id, response: 'decline', requestedFollowupAt: null }))
    assert.equal(declined.preferences.allowProgramInvitations, false)
    const optedIn = unwrap(await service.updatePreferences({ profileId: 'inactive-31-60', requestId: 'opt-in' }, { ...declined.preferences, allowProgramInvitations: true }))
    assert.equal(optedIn.contactPermission.reason, 'rejected')
    const started = unwrap(await service.startProgram({ profileId: 'inactive-31-60', requestId: 'voluntary' }, { origin: 'app' }))
    assert.equal(started.progress.eligibleAtStart, true)
    assert.equal(started.progress.origin, 'app')
  })
  test(`${name}: help does not resolve cases, progress and explicit connection are separate`, async () => {
    const { service, admin } = create(); let n = 0
    const ctx = () => ({ profileId: 'inactive-recent', requestId: `help-${++n}` })
    let snapshot = unwrap(await service.getProfile('inactive-recent'))
    const caseId = snapshot.cases[0].id
    snapshot = unwrap(await service.requestHelp(ctx(), { caseId }))
    assert.equal(snapshot.cases[0].status, 'pending')
    assert.equal(snapshot.helpRequests.length, 1)
    snapshot = unwrap(await service.requestHelp(ctx(), { caseId }))
    assert.equal(snapshot.helpRequests.length, 1)
    snapshot = unwrap(await admin.setCaseStatus(ctx(), { caseId, status: 'resolved' }))
    assert.equal(snapshot.cases[0].status, 'resolved')
    expectError(await service.requestHelp(ctx(), { caseId }), 'CONFLICT')
    snapshot = unwrap(await service.updateProgress(ctx(), { step: 'decision', need: 'time', otherNeedDetail: '', configuration }))
    assert.equal(snapshot.progress.need, 'time')
    assert.ok(snapshot.mentor.actions.includes('shorten'))
    expectError(await service.confirmConnection(ctx(), { explicitConsent: false }), 'VALIDATION')
    snapshot = unwrap(await service.confirmConnection(ctx(), { explicitConsent: true }))
    assert.equal(snapshot.progress.connectedAt, referenceAt)
    assert.equal(snapshot.progress.returnedAt, null)
    assert.equal(snapshot.progress.interventionStartedAt, null)
    snapshot = unwrap(await service.disconnect(ctx()))
    assert.equal(snapshot.progress.connectedAt, null)
    expectError(await service.confirmConnection({ profileId: 'blocked', requestId: 'blocked-connect' }, { explicitConsent: true }), 'NOT_ELIGIBLE')
  })
  test(`${name}: return requires eligible start and subsequent completed delivery, deduplicated by id`, async () => {
    const { service, admin } = create(); let n = 0
    const ctx = () => ({ profileId: 'inactive-recent', requestId: `return-${++n}` })
    const started = unwrap(await service.startProgram(ctx(), { origin: 'external' }))
    assert.equal(started.progress.returnedAt, null)
    expectError(await service.recordReturnFeedback(ctx(), { feedback: 'good' }), 'CONFLICT')
    unwrap(await admin.registerDelivery(ctx(), { id: 'at-start', status: 'completed', completedAt: referenceAt }))
    assert.equal(unwrap(await service.getProfile('inactive-recent')).progress.returnedAt, null)
    unwrap(await admin.advanceClock({ observedAt: '2026-10-01T15:02:00.000Z' }))
    unwrap(await admin.registerDelivery(ctx(), { id: 'cancelled', status: 'cancelled', completedAt: '2026-10-01T15:01:00.000Z' }))
    assert.equal(unwrap(await service.getProfile('inactive-recent')).progress.returnedAt, null)
    const delivery = { id: 'return', status: 'completed', completedAt: '2026-10-01T15:02:00.000Z' }
    let snapshot = unwrap(await admin.registerDelivery(ctx(), delivery))
    assert.equal(snapshot.progress.returnDeliveryId, 'return')
    snapshot = unwrap(await admin.registerDelivery(ctx(), delivery))
    assert.equal(snapshot.deliveries.filter(d => d.id === 'return').length, 1)
    expectError(await admin.registerDelivery(ctx(), { ...delivery, status: 'cancelled' }), 'CONFLICT')
    snapshot = unwrap(await service.recordReturnFeedback(ctx(), { feedback: 'good' }))
    assert.equal(snapshot.progress.returnFeedback, 'good')
    assert.deepEqual(snapshot.contributions, [])
    expectError(await service.startProgram({ profileId: 'interruption-10', requestId: 'preventive-start' }, { origin: 'app' }), 'NOT_ELIGIBLE')
    expectError(await service.startProgram({ profileId: 'blocked', requestId: 'blocked-start' }, { origin: 'app' }), 'NOT_ELIGIBLE')
    expectError(await admin.registerDelivery(ctx(), { id: 'future', status: 'completed', completedAt: '2026-10-02T15:00:00.000Z' }), 'VALIDATION')
  })
  test(`${name}: reminders require permission, execute due once, and deletion removes them`, async () => {
    const { service, admin } = create(); let n = 0
    const ctx = () => ({ profileId: 'inactive-recent', requestId: `reminder-${++n}` })
    const projection = unwrap(await service.calculateProjection(ctx(), configuration))
    const saved = unwrap(await service.saveOption(ctx(), { projectionId: projection.id }))
    const savedOptionId = saved.savedOptions[0].id
    expectError(await service.scheduleReminder(ctx(), { savedOptionId, scheduledAt: '2026-10-02T13:30:00.000Z', explicitConsent: true }), 'CONTACT_BLOCKED')
    unwrap(await service.updatePreferences(ctx(), { ...saved.preferences, remindersAllowed: true }))
    let snapshot = unwrap(await service.scheduleReminder(ctx(), { savedOptionId, scheduledAt: '2026-10-02T13:30:00.000Z', explicitConsent: true }))
    const reminderId = snapshot.reminders[0].id
    expectError(await admin.executeReminder(ctx(), { reminderId }), 'VALIDATION')
    snapshot = unwrap(await service.scheduleReminder(ctx(), { savedOptionId, reminderId, scheduledAt: '2026-10-02T14:00:00.000Z', explicitConsent: true }))
    assert.equal(snapshot.reminders.length, 1)
    assert.equal(snapshot.reminders[0].scheduledAt, '2026-10-02T14:00:00.000Z')
    unwrap(await admin.advanceClock({ observedAt: '2026-10-02T14:00:00.000Z' }))
    snapshot = unwrap(await admin.executeReminder(ctx(), { reminderId }))
    const executedAt = snapshot.reminders[0].executedAt
    assert.equal(executedAt, '2026-10-02T14:00:00.000Z')
    snapshot = unwrap(await admin.executeReminder(ctx(), { reminderId }))
    assert.equal(snapshot.reminders[0].executedAt, executedAt)
    snapshot = unwrap(await service.deleteOption(ctx(), { optionId: savedOptionId }))
    assert.deepEqual(snapshot.reminders, [])
    expectError(await admin.executeReminder(ctx(), { reminderId }), 'NOT_FOUND')
  })
  test(`${name}: resets are profile scoped or complete, restoring all initial entities`, async () => {
    const { service, admin } = create()
    const input = { name: 'Meta', targetAmount: 50, targetDate: null }
    unwrap(await service.saveGoal({ profileId: 'inactive-recent', requestId: 'camila' }, input))
    const marco = unwrap(await service.saveGoal({ profileId: 'inactive-31-60', requestId: 'marco' }, input))
    const reset = unwrap(await admin.resetProfile('inactive-recent'))
    assert.deepEqual(reset.goals, [])
    assert.deepEqual(unwrap(await service.getProfile('inactive-31-60')), marco)
    unwrap(await admin.advanceClock({ observedAt: '2026-10-05T15:00:00.000Z' }))
    const clean = unwrap(await admin.resetDemo())
    assert.equal(clean.profile.id, 'inactive-recent')
    assert.equal(clean.clock.observedAt, referenceAt)
    assert.deepEqual(unwrap(await service.getProfile('inactive-31-60')).goals, [])
    assert.equal(unwrap(await service.getProfile('declared-pause')).pause.status, 'active')
  })
}
