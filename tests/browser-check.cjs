const button = (page, name) => phone(page).getByRole('button', { name, exact: true })
async function data(page, id = 'inactive-recent') { return page.evaluate(({key,id}) => JSON.parse(sessionStorage.getItem(key)).profileDataById[id], {key,id}) }
async function controls(page) {
  const panel = page.locator('.presenter-panel')
  if (!await panel.evaluate(element => element.open)) await panel.locator(':scope > summary').click()
  return page.locator('.presenter-sidebar')
}
async function home(page) { await (await controls(page)).getByRole('button', { name: /Ver inicio del repartidor/ }).click(); await phone(page).locator('.welcome-section').waitFor() }
async function start(page) {
  await page.goto(base + '/')
  await button(page, 'Calcular cuánto podría generar').click()
  await phone(page).getByRole('heading', { name: 'Tu tiempo y zona', exact: true }).waitFor()
}
async function estimate(page) {
  await start(page)
  await button(page, 'Calcular estimación').click()
  await phone(page).getByRole('heading', { name: 'Tu estimación', exact: true }).waitFor()
}
async function noOverflow(page) {
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'document overflows')
  const screen = phone(page)
  if (await screen.count()) {
    assert.equal(await screen.evaluate(element => element.scrollWidth <= element.clientWidth), true, 'phone content overflows')
    const clipped = await screen.evaluate(screen => {
      const bounds = screen.getBoundingClientRect()
      return [...screen.querySelectorAll('input,select,button,textarea')].filter(element => element.getClientRects().length && (element.getBoundingClientRect().left < bounds.left - 1 || element.getBoundingClientRect().right > bounds.right + 1)).map(element => element.outerHTML.slice(0,120))
    })
    assert.deepEqual(clipped, [], 'phone controls are clipped horizontally')
  }
}
async function reminder(page) {
  const saved = phone(page).locator('.need-saved-proposal').last()
  if (!await saved.evaluate(element => element.open)) await saved.locator(':scope > summary').click()
  const editor = saved.locator('.proposal-reminder')
  await editor.getByRole('checkbox', { name: 'Quiero un recordatorio', exact: true }).check()
  await editor.locator('input[type=date]').fill('2026-10-02')
  await editor.locator('input[type=time]').fill('08:30')
  await editor.getByRole('button', { name: 'Guardar recordatorio', exact: true }).click()
  return editor
}

